"""Non-executing diagnostic dump of the normal python-direct preparation path."""
from pathlib import Path, PureWindowsPath
import unicodedata


def _portable_name(name):
    # Apply Windows filename rules even when producing an artifact on Linux.
    if (not name or any(ord(c) < 32 or c in '<>:"/\\|?*' for c in name)
            or name.endswith((' ', '.')) or PureWindowsPath(name).is_reserved()):
        raise ValueError('непереносимое имя выходного файла: ' + repr(name))
    return unicodedata.normalize('NFC', name).casefold()


def sources(prepared):
    """Only plans created by this preparation; never load or execute imports."""
    result = {'': prepared._plan.generated_source}
    module = prepared._exports
    if module is not None:
        for suffix, attribute in (
                ('.server', 'server_plan'),
                ('.server-nocontext', 'nocontext_plan'),
                ('.dual-client', 'dual_plan'),
                ('.server-init', 'initializer_plan')):
            plan = getattr(module, attribute)
            if plan is not None:
                result[suffix] = plan.generated_source
    return result


def emit_file(source, directory, *, encoding='utf-8-sig', profile='standalone'):
    from yadinassi.runtime import Interpreter
    source, directory = Path(source), Path(directory)
    # Read only the explicitly selected input. No import traversal or database.
    text = source.read_text(encoding=encoding)
    vm = Interpreter(encoding=encoding, execution_backend='python-direct', compilation_profile=profile)
    vm._standalone_import_links = True
    try:
        compiled = sources(vm.prepare(text, str(source)))
    finally:
        vm.close()
    outputs = {source.stem + suffix + '.py': code for suffix, code in compiled.items()}
    names = {_portable_name(name) for name in outputs}
    if len(names) != len(outputs):
        raise FileExistsError('совпадающие имена выходных файлов')
    if directory.exists():
        existing = {unicodedata.normalize('NFC', p.name).casefold() for p in directory.iterdir()}
        if names & existing:
            raise FileExistsError('выходной файл уже существует (без учёта регистра); выберите другой каталог')
    directory.mkdir(parents=True, exist_ok=True)
    opened = []
    try:
        # Reserve every output before writing. Exclusive creation also handles
        # ordinary concurrent same-path creation; never truncate existing data.
        for name in outputs:
            path = directory / name
            opened.append((path, path.open('x', encoding='utf-8', newline='\n')))
        for path, stream in opened:
            stream.write('# Generated by yadinassi --emit-python; backend: python-direct\n'
                         '# Diagnostic source, not a standalone program. Requires the yadinassi\n'
                         '# runtime namespace, constant pool and execution context. BSL was not run.\n'
                         '# Source: ' + repr(str(source)) + '\n\n')
            stream.write(outputs[path.name] + '\n')
    except BaseException:
        for path, stream in opened:
            stream.close()
            path.unlink()
        raise
    else:
        for _, stream in opened:
            stream.close()
    return [path for path, _ in opened]


def run(args, parser):
    import sys
    from yadinassi.types.errors import BSLError
    allowed = {'file', 'emit_python', 'encoding', 'preprocessor_profile', 'execution_backend'}
    if not args.file or args.file == '-' or not args.emit_python:
        parser.error('--emit-python требует один файл BSL и непустой выходной каталог')
    if args.execution_backend != 'python-direct' or any(
            value is not None and value is not False for key, value in vars(args).items()
            if key not in allowed):
        parser.error('--emit-python не совмещается с legacy, командой, базой данных или другими режимами')
    try:
        outputs = emit_file(args.file, args.emit_python, encoding=args.encoding,
                            profile=args.preprocessor_profile)
    except (BSLError, OSError, UnicodeError, LookupError, ValueError, TypeError, RecursionError) as error:
        print('yadinassi: --emit-python: ' + str(error), file=sys.stderr)
        return 1
    for path in outputs:
        print(path)
    return 0
