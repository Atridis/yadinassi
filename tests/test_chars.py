"""Finite Chars members observed in native run 39743653257 (PR80)."""
from dataclasses import FrozenInstanceError
from pathlib import Path
import hashlib
import json
import subprocess
import sys
import tempfile
import unittest

from yadinassi import Interpreter
from yadinassi.chars import CHARS
from yadinassi.errors import BSLRuntimeError
from yadinassi.serialization import value_from_string_internal, value_to_string_internal
from yadinassi.type_values import type_of
from yadinassi.values import BSLType
from yadinassi.xml_values import xml_string, xml_value

# Copied from native codepoint projections, not generated by the interpreter.
MEMBERS = (("ВК", "CR", 13), ("ВТаб", "VTab", 11), ("НПП", "NBSp", 160),
           ("ПС", "LF", 10), ("ПФ", "FF", 12), ("Таб", "Tab", 9))


class CharsTests(unittest.TestCase):
    def setUp(self):
        self.vm = Interpreter(lambda text: None)

    def test_exact_bilingual_members_return_ordinary_strings(self):
        for ru, en, code in MEMBERS:
            for namespace in ("Символы", "Chars", "сИмВоЛы", "cHaRs"):
                for member in (ru, en, ru.swapcase(), en.swapcase()):
                    with self.subTest(namespace=namespace, member=member):
                        value = self.vm.execute(f'{namespace}.{member}')
                        self.assertIs(type(value), str)
                        self.assertEqual((len(value), ord(value)), (1, code))
                        self.assertIs(type_of(value), BSLType.STRING)

    def test_string_indices_use_only_the_closed_readonly_member_set(self):
        for ru, en, code in MEMBERS:
            for namespace in ('Символы', 'Chars'):
                for member in (ru, en, ru.swapcase(), en.swapcase()):
                    with self.subTest(namespace=namespace, member=member):
                        expression = f'{namespace}["{member}"]'
                        self.assertEqual(self.vm.execute(expression), chr(code))
                        with self.assertRaises(BSLRuntimeError):
                            self.vm.execute(expression + ' = "changed";')
                        self.assertEqual(self.vm.execute(expression), chr(code))
        for index in ('"Missing"', '"__class__"', '"Count"', '" LF"', '0',
                      'True', 'Undefined', 'New Array'):
            for source in (f'Chars[{index}]', f'Chars[{index}] = "bad";'):
                with self.subTest(source=source), self.assertRaises(BSLRuntimeError):
                    self.vm.execute(source)
        self.assertEqual(self.vm.execute('Chars.LF'), '\n')

    def test_non_string_host_indices_do_not_invoke_conversion_hooks(self):
        calls = []
        class HostIndex:
            def __str__(self):
                calls.append('str')
                return 'LF'
        with self.assertRaises(TypeError):
            CHARS.get_index(HostIndex())
        self.assertEqual(calls, [])

    def test_readonly_and_closed_members(self):
        for ru, en, code in MEMBERS:
            for member in (ru, en):
                with self.assertRaises(BSLRuntimeError):
                    self.vm.execute(f'Chars.{member} = "changed";')
                self.assertEqual(self.vm.execute(f'Chars.{member}'), chr(code))
        for name in ('Missing', '__class__', '__dict__', 'get_member', 'items', 'Count'):
            with self.subTest(name=name), self.assertRaises(BSLRuntimeError):
                self.vm.execute('Chars.' + name)
        with self.assertRaises(FrozenInstanceError):
            CHARS.extra = 'bad'

    def test_no_unmeasured_constructor_enumeration_or_namespace_codec(self):
        for source in ('Chars()', 'Chars.LF()', 'New Chars', 'New Символы',
                       'Chars[0]', 'For Each Item In Chars Do EndDo;',
                       'TypeOf(Chars)', 'ValueToStringInternal(Chars)',
                       'String(Chars)', 'Строка(Символы)', 'Message(Chars)',
                       '"prefix=" + Chars', 'XMLString(Chars)'):
            with self.subTest(source=source), self.assertRaises(BSLRuntimeError):
                self.vm.execute(source)

    def test_member_internal_and_xml_scalar_roundtrips(self):
        # Scalar XML conversion is not an XML document character-validity test.
        for ru, en, code in MEMBERS:
            value = CHARS.get_member(en)
            self.assertEqual(value_from_string_internal(value_to_string_internal(value)), value)
            self.assertEqual(xml_value(BSLType.STRING, xml_string(value)), value)
            self.assertEqual(ord(value), code)

    def test_eval_execute_and_receiver(self):
        self.assertEqual(self.vm.execute('Eval("сИмВоЛы.пС")'), '\n')
        self.vm.execute('result = Undefined; Execute("result = Chars.Tab;");')
        self.assertEqual(self.vm.variables['result'], '\t')
        self.vm.execute('Function Pick(namespace) Return namespace.LF; EndFunction')
        self.assertEqual(self.vm.execute('Pick(Chars)'), '\n')
        self.assertEqual(self.vm.execute('Pick(Символы)'), '\n')

    def test_variable_parameter_routine_and_host_function_shadowing(self):
        self.vm.execute('Chars = New Structure("LF", "local");')
        self.assertEqual(self.vm.execute('chars.LF'), 'local')
        self.assertEqual(self.vm.execute('Символы.ПС'), '\n')
        self.vm.execute('Function Pick(Символы) Return Символы; EndFunction')
        self.assertEqual(self.vm.execute('Pick("parameter")'), 'parameter')
        other = Interpreter(lambda text: None)
        other.execute('Function Chars() Return "routine"; EndFunction')
        self.assertEqual(other.execute('Chars()'), 'routine')
        with self.assertRaises(BSLRuntimeError):
            other.execute('Chars.LF')
        host = Interpreter(lambda text: None)
        host.register_function('Chars', lambda: 'host')
        self.assertEqual(host.execute('Chars()'), 'host')
        with self.assertRaises(BSLRuntimeError):
            host.execute('Chars.LF')

    def test_complete_checkpoint_matches_native_observations(self):
        root = Path(__file__).resolve().parents[1]
        fixture = json.loads((root / 'tests/fixtures/chars_namespace_linux.json').read_text(encoding="utf-8"))
        self.assertEqual(fixture['native_run'], 39746207974)
        self.assertEqual(fixture['server_and_managed_client_message_count'], 361)
        source = (root / 'integrational_tests/tests/values.bsl').read_text(encoding="utf-8")
        self.assertEqual(hashlib.sha256(source.encode()).hexdigest(), fixture['source_sha256'])
        output = []
        vm = Interpreter(output.append)
        vm.execute(source)
        actual = [record for record in output if record.startswith('chars.')]
        expected = fixture['records']
        self.assertEqual(len(expected), 100)
        self.assertEqual(len(output), 361)
        self.assertEqual(actual, expected)

    def test_namespace_presentation_error_keeps_repl_usable(self):
        root = Path(__file__).resolve().parents[1]
        result = subprocess.run([sys.executable, '-m', 'yadinassi'],
                                input='Chars\nMessage(42);\n/exit\n',
                                capture_output=True, encoding='utf-8', cwd=root, timeout=10)
        self.assertEqual(result.returncode, 1)
        self.assertEqual(result.stdout, '42\n')
        self.assertIn('пока не поддерживается', result.stderr)
        self.assertNotIn('Traceback', result.stderr)

    def test_client_routines_share_the_namespace(self):
        self.vm.execute('&AtClient\nFunction ReadEn() Return Chars.CR; EndFunction\n'
                        '&НаКлиенте\nFunction ReadRu() Return Символы.ВК; EndFunction')
        self.assertEqual(self.vm.execute('ReadEn()'), '\r')
        self.assertEqual(self.vm.execute('ReadRu()'), '\r')

    def test_imported_routine_uses_namespace(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory)
            (path / 'helper.bsl').write_text('Function Read() Export Return Chars.LF; EndFunction', encoding='utf-8')
            source = path / 'main.bsl'
            source.write_text('// #Import helper.bsl\nresult = helper.Read();', encoding='utf-8')
            self.vm.execute(source.read_text(encoding="utf-8"), source=str(source))
            self.assertEqual(self.vm.variables['result'], '\n')


if __name__ == '__main__':
    unittest.main()
