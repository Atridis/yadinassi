def pair(name):
    first, second = TD('Number'), TD('Number')
    if name == 'same-object':
        second = first
    elif name == 'equal-empty':
        first, second = TD(), TD()
    elif name == 'equal-reordered':
        first, second = TD('Number,String'), TD('String,Number')
    elif name == 'equal-copy':
        second = TD(first)
    elif name == 'unequal-types':
        second = TD('String')
    elif name == 'unequal-number-qualifiers':
        first, second = TD('Number', NQ(D(5), D(2))), TD('Number', NQ(D(5), D(1)))
    elif name == 'unequal-string-qualifiers':
        first = TD('String', None, SQ(D(4), AL.FIXED))
        second = TD('String', None, SQ(D(4), AL.VARIABLE))
    elif name != 'equal-number':
        raise AssertionError('unknown measured pair')
    return first, second


def canonical_source(raw):
    # Checkout portability only, never a normalization of native output bytes.
    return raw.decode('utf-8-sig').replace('\r\n', '\n').encode('utf-8-sig')


def native_history(label):
    records = read_observation(extract_payload(
        NATIVE_SUFFIX, 'table.descriptor-key.' + label))
    result = {}
    for step in records.items:
        name, separator, payload = step.partition(':ok:')
        if not separator:
            raise AssertionError('codec step did not succeed: ' + step)
        if name in result:
            raise AssertionError('duplicate codec step: ' + name)
        # The nested history uses the compact scalar escape layer. Decode it
        # once, preserving literal native codec newlines and entry order.
        result[name] = read_observation(payload, compact=True)
    return result


class DescriptorMapNativeRuntimeTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.raw = (ROOT / 'integrational_tests/tests/collections.bsl').read_bytes()
        cls.source = canonical_source(cls.raw).decode('utf-8-sig')
        cls.actual = []
        Interpreter(cls.actual.append).execute(cls.source)

    def test_native_suffix_hash_and_complete_31_record_exact_replay(self):
        self.assertEqual(hashlib.sha256(NATIVE_SUFFIX.encode('utf-8')).hexdigest(),
                         NATIVE_SUFFIX_SHA256)
        expected = NATIVE_SUFFIX.splitlines()
        labels = [f'table.descriptor-key.{mode}.{name}' for name in PAIRS
                  for mode in ('equality', 'mutable', 'fixed-copy')]
        labels += [f'table.descriptor-key.codec-{kind}-{variant}'
                   for variant in ('single', 'unequal', 'duplicate-equal')
                   for kind in ('mutable', 'fixed')]
        labels.append('table.descriptor-key.checkpoint.complete')
        self.assertEqual(len(expected), 31)
        self.assertEqual([record.split(':', 1)[0] for record in expected], labels)
        self.assertEqual(len(self.actual), 828)
        # No map-order exceptions, omission of error steps, or output rewriting.
        self.assertEqual(self.actual[797:], expected)
        self.assertEqual(expected[-1], 'table.descriptor-key.checkpoint.complete: [ok]')

    def test_source_provenance_pin_accepts_lf_and_crlf_checkout_only(self):
        lf = self.source.encode('utf-8-sig')
        for raw in (self.raw, lf, lf.replace(b'\n', b'\r\n')):
            with self.subTest(crlf=b'\r\n' in raw):
                self.assertEqual(hashlib.sha256(canonical_source(raw)).hexdigest(),
                                 SOURCE_SHA256)
        # A changed probe or helper must not inherit the same provenance pin.
        for mutant in (lf + b'\n', lf.replace(b'101', b'102', 1),
                       lf.replace(b'equal-empty', b'equal-changed', 1)):
            self.assertNotEqual(hashlib.sha256(canonical_source(mutant)).hexdigest(),
                                SOURCE_SHA256)

    def test_all_six_native_codec_payloads_and_readback_lookups(self):
        for variant in ('single', 'unequal', 'duplicate-equal'):
            for kind, constructor in (('mutable', BSLMap), ('fixed', BSLFixedMap)):
                label = 'codec-' + kind + '-' + variant
                with self.subTest(label=label):
                    measured = native_history(label)
                    first, second = pair('unequal-types' if variant == 'unequal'
                                         else 'equal-number')
                    source = BSLMap()
                    source.insert(first, D(101))
                    if variant != 'single':
                        source.insert(second, D(202))
                    original = source if constructor is BSLMap else constructor(source)
                    payload = measured['codec-write']
                    self.assertIs(type(payload), str)
                    self.assertEqual(write(original), payload)
                    self.assertEqual(D(len(original._items)), measured['codec-source-count'])
                    restored = read(payload)
                    self.assertIs(type(restored), constructor)
                    self.assertIsNot(restored, original)
                    self.assertIs(type_of(restored), measured['codec-read'])
                    self.assertEqual(D(len(restored._items)), measured['codec-count'])
                    self.assertEqual(restored.get(first), measured['codec-first'])
                    self.assertEqual(restored.get(second), measured['codec-second'])
                    vm = Interpreter(lambda _: None)
                    vm.variables.update(restored=restored, first=first, second=second)
                    self.assertEqual(vm.execute('restored[first]'), measured['codec-index-first'])
                    self.assertEqual(vm.execute('restored[second]'), measured['codec-index-second'])
                    for entry in restored:
                        self.assertIs(type(entry.key), TD)
                        self.assertIsNot(entry.key, first)
                        self.assertIsNot(entry.key, second)

    def test_native_two_key_stream_order_is_not_normalized(self):
        mutable = native_history('codec-mutable-unequal')['codec-write']
        fixed = native_history('codec-fixed-unequal')['codec-write']
        # These are distinct measured streams, not an inferred iteration rule.
        self.assertLess(mutable.index('{"S"}'), mutable.index('{"N"}'))
        self.assertLess(fixed.index('{"N"}'), fixed.index('{"S"}'))
        self.assertNotEqual(mutable.replace(MAP_IDS[BSLMap], MAP_IDS[BSLFixedMap]), fixed)


class DescriptorMapKeyContractTests(unittest.TestCase):
    def test_measured_equal_and_unequal_pairs_share_all_mutable_operations(self):
        for name in PAIRS:
            with self.subTest(pair=name):
                first, second = pair(name)
                equal_keys = not name.startswith('unequal-')
                mapping = BSLMap()
                vm = Interpreter(lambda _: None)
                vm.variables.update(m=mapping, first=first, second=second)
                self.assertIsNone(mapping.get(first))
                mapping.delete(second)
                self.assertEqual(len(mapping._items), 0)
                mapping.insert(first, D(101))
                self.assertEqual(vm.execute('m[first]'), D(101))
                self.assertEqual(mapping.get(second), D(101) if equal_keys else None)
                self.assertEqual(vm.execute('m[second]'), D(101) if equal_keys else None)
                mapping.insert(second, D(202))
                self.assertEqual(len(mapping._items), 1 if equal_keys else 2)
                self.assertEqual(mapping.get(first), D(202) if equal_keys else D(101))
                vm.execute('m[second] = 303;')
                self.assertEqual(len(mapping._items), 1 if equal_keys else 2)
                self.assertEqual(mapping.get(first), D(303) if equal_keys else D(101))
                self.assertEqual(mapping.get(second), D(303))
                mapping.delete(second)
                self.assertEqual(len(mapping._items), 0 if equal_keys else 1)
                self.assertIsNone(mapping.get(second))
                self.assertEqual(mapping.get(first), None if equal_keys else D(101))
                mapping.delete(first)
                self.assertEqual(len(mapping._items), 0)

    def test_snapshot_and_mutable_copy_are_isolated_for_every_measured_pair(self):
        for name in PAIRS:
            with self.subTest(pair=name):
                first, second = pair(name)
                equal_keys = not name.startswith('unequal-')
                source = BSLMap()
                source.insert(first, D(101))
                fixed = BSLFixedMap(source)
                copied = BSLMap(fixed)
                source.set(first, D(404))
                source.delete(first)
                self.assertEqual(len(source._items), 0)
                self.assertEqual(fixed.get(first), D(101))
                self.assertEqual(copied.get(first), D(101))
                copied.insert(second, D(505))
                self.assertEqual(len(copied._items), 1 if equal_keys else 2)
                self.assertEqual(copied.get(first), D(505) if equal_keys else D(101))
                self.assertEqual(copied.get(second), D(505))
                self.assertEqual(len(fixed._items), 1)
                self.assertEqual(fixed.get(first), D(101))
                self.assertEqual(fixed.get(second), D(101) if equal_keys else None)
                copied.clear()
                self.assertEqual(len(copied._items), 0)
                self.assertEqual(fixed.get(first), D(101))

    def test_fixed_missing_descriptor_index_differs_from_get_and_existing_undefined(self):
        source = BSLMap()
        source.insert(TD('Number'))
        fixed = BSLFixedMap(source)
        vm = Interpreter(lambda _: None)
        vm.variables.update(fixed=fixed, existing=TD('Number'), absent=TD('String'))
        self.assertIsNone(fixed.get(TD('Number')))
        self.assertIsNone(fixed.get(TD('String')))
        self.assertIsNone(vm.execute('fixed[existing]'))
        with self.assertRaisesRegex(BSLRuntimeError, 'Ключ фиксированного соответствия не найден'):
            vm.execute('fixed[absent]')
        for expression in ('fixed[existing] = 1;', 'fixed[absent] = 2;'):
            with self.assertRaisesRegex(BSLRuntimeError, 'недоступны для записи'):
                vm.execute(expression)
        self.assertEqual(len(fixed._items), 1)
        self.assertIsNone(fixed.get(TD('Number')))

    def test_descriptor_keys_do_not_alias_scalar_type_values_or_identity_objects(self):
        keys = [TD('Number'), BSLType.NUMBER, D(1), True, 'Number', None, NULL,
                BSLDate(0), [], [], BSLArray(), BSLArray(), NQ(D(5)), NQ(D(5))]
        mapping = BSLMap()
        for index, key in enumerate(keys):
            mapping.insert(key, D(index))
        self.assertEqual(len(mapping._items), len(keys))
        mapping.set(TD('Number'), D(99))
        self.assertEqual(len(mapping._items), len(keys))
        self.assertEqual(mapping.get(keys[0]), D(99))
        keys[8].append('mutation')
        keys[10].add(D(5))
        for index, key in enumerate(keys[1:], 1):
            self.assertEqual(mapping.get(key), D(index))
        self.assertIsNone(mapping.get([]))
        self.assertIsNone(mapping.get(NQ(D(5))))
        mapping.delete(TD('Number'))
        self.assertIsNone(mapping.get(keys[0]))
        self.assertEqual(mapping.get(BSLType.NUMBER), D(1))

    def test_descriptor_subclasses_and_host_metaclasses_keep_identity_without_hooks(self):
        def forbidden(*args, **kwargs):
            raise AssertionError('host equality/hash must not participate in map keys')

        class HostileMeta(type):
            __eq__ = __ne__ = __hash__ = forbidden

        class HostileDescriptor(TD, metaclass=HostileMeta):
            __eq__ = __ne__ = __hash__ = forbidden

        class PlainDescriptor(TD):
            pass

        keys = [TD('Number'), HostileDescriptor('Number'), HostileDescriptor('Number'),
                PlainDescriptor('Number'), PlainDescriptor('Number')]
        mapping = BSLMap()
        for index, key in enumerate(keys):
            mapping.insert(key, D(index))
        fixed = BSLFixedMap(mapping)
        copied = BSLMap(fixed)
        self.assertEqual(len(mapping._items), 5)
        self.assertIsNone(mapping.get(HostileDescriptor('Number')))
        self.assertIsNone(mapping.get(PlainDescriptor('Number')))
        for index, key in enumerate(keys):
            for collection in (mapping, fixed, copied):
                self.assertEqual(collection.get(key), D(index))
            mapping.set(key, D(index + 10))
            self.assertEqual(mapping.get(key), D(index + 10))
            mapping.delete(key)
            self.assertIsNone(mapping.get(key))
            self.assertEqual(fixed.get(key), D(index))
        self.assertEqual(len(mapping._items), 0)

    def test_descriptor_and_qualifier_immutability_keep_inserted_keys_stable(self):
        types = BSLArray()
        types.add(BSLType.STRING)
        types.add(BSLType.NUMBER)
        descriptor = TD(types, NQ(D(5), D(2)), SQ(D(4), AL.FIXED))
        same = TD('Number,String', NQ(D(5), D(2)), SQ(D(4), AL.FIXED))
        mapping = BSLMap()
        mapping.insert(descriptor, 'kept')
        initial_hash = hash(descriptor)
        types.items.clear()
        descriptor.get_types().items.clear()
        for value, field, replacement in (
            (descriptor, 'types', (BSLType.BOOLEAN,)),
            (descriptor, 'number_qualifiers', NQ()),
            (descriptor.number_qualifiers, 'digits', D(8)),
            (descriptor.string_qualifiers, 'length', D(8)),
            (descriptor.date_qualifiers, 'date_fractions', DF.TIME),
        ):
            with self.subTest(field=field), self.assertRaises(FrozenInstanceError):
                setattr(value, field, replacement)
        self.assertEqual(hash(descriptor), initial_hash)
        self.assertEqual(hash(descriptor), hash(same))
        self.assertEqual(mapping.get(same), 'kept')
        self.assertEqual(mapping.get(TD(descriptor)), 'kept')
        self.assertEqual(len(mapping._items), 1)

    def test_local_scalar_subset_and_qualifier_distinctions_remain_bounded(self):
        # Local state-space checks, not claims of new native map-key probes.
        keys = [TD(), TD('Boolean'), TD('String'), TD('Date'), TD('Number'),
                TD('Null'), TD('Boolean,String,Date,Number'),
                TD('Number', NQ(D(5), D(2), AS.NONNEGATIVE)),
                TD('Number', NQ(D(5), D(2), AS.ANY)),
                TD('Date', None, None, DQ(DF.DATE)),
                TD('Date', None, None, DQ(DF.TIME))]
        mapping = BSLMap()
        for index, key in enumerate(keys):
            mapping.insert(key, D(index))
        self.assertEqual(len(mapping._items), len(keys))
        for index, key in enumerate(keys):
            self.assertEqual(mapping.get(TD(key)), D(index))
        for unsupported in ('Map', 'Array', 'BinaryData', 'UUID', 'Null,Number'):
            with self.subTest(type=unsupported), self.assertRaises(ValueError):
                TD(unsupported)
        self.assertEqual(len(mapping._items), len(keys))

    def test_handcrafted_duplicate_equal_descriptor_stream_collapses_without_reader_regression(self):
        descriptor = write(TD('Number'))
        for constructor, identifier in MAP_IDS.items():
            with self.subTest(kind=constructor.__name__):
                # Explicit decoder-policy test: two stream entries with equal
                # keys, rather than the native writer's already-collapsed one.
                payload = ('{"#",' + identifier + ',{2,{' + descriptor +
                           ',{"N",101}},{' + descriptor + ',{"N",202}}}}')
                restored = read(payload)
                self.assertIs(type(restored), constructor)
                self.assertEqual(len(restored._items), 1)
                self.assertEqual(restored.get(TD('Number')), D(202))
                native = native_history('codec-' + ('mutable' if constructor is BSLMap
                                                    else 'fixed') + '-duplicate-equal')
                self.assertEqual(write(restored), native['codec-write'])
                malformed = [payload[:-1], payload.replace(',{2,', ',{3,', 1),
                             payload.replace('{"Pattern",', '{"UnknownPattern",', 1)]
                for bad in malformed:
                    with self.assertRaisesRegex(ValueError, FORMAT_ERROR):
                        read(bad)
                self.assertEqual(read(payload).get(TD('Number')), D(202))


