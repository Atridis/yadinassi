ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / 'integrational_tests/fill_exclude_native'
SOURCE_SHA256 = '42c1fedddb8a689f3ba2ca6a241b1d19d38c0bea4da8a29e5934b3082a43fdfb'
OUTPUT_SHA256 = 'ac37b8113282a5624f71a9608fa9db38f14db0045f4501915c008c3f9e0c133a'
SUFFIX_SHA256 = '9ab3247753a786df60feeb6bf724db4aadd452ba2c05b0be953a216cd42da6f8'
MISSING_GUARD = 'Отсутствующие исключаемые свойства пока не поддерживаются'
TARGETS = (None, WINDOWS_8_3_27_2342, LINUX_8_3_27_1508)
MAP_LABELS = tuple(base + suffix for base in (
    'internal.map.typed-keys', 'internal.map.typed-keys-again',
    'internal.map.reverse-insertion', 'internal.array.nested',
) for suffix in ('.payload', '.roundtrip.payload'))
PROBES = tuple(('fill.exclude-missing.' + label, variant, excluded, 'last')
               for label, variant, excluded in CASES) + tuple(
    ('fill.exclude-source-order.source-only.' + position, 'source-only',
     'Missing', position) for position in ('first', 'between'))


def make_pair(variant='source-only', position='last'):
    destination = BSLStructure('First,Last,Copy', 1, 2, 3)
    items = [('First', 10), ('Last', 20), ('Copy', 30)]
    if variant == 'source-only':
        items.insert({'first': 0, 'between': 1, 'last': 3}[position], ('Missing', 40))
    if variant == 'target-only':
        destination.insert('Missing', 4)
    source = BSLStructure()
    for name, value in items:
        source.insert(name, value)
    return destination, source


def state(destination, status):
    missing = destination.property('Missing')
    return dict(status=status, first=destination.get('First'),
                last=destination.get('Last'), copy=destination.get('Copy'),
                target_count=len(destination._items), target_missing=missing,
                target_missing_value=destination.get('Missing') if missing else None)


def invoke(destination, source, exclude, target=None, include=None):
    with target_context(target) if target is not None else nullcontext():
        try:
            fill_property_values(destination, source, include, exclude)
        except (TypeError, ValueError):
            return state(destination, 'error')
    return state(destination, 'ok')


class FillExcludeNativeRuntimeTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.native = json.loads((FIXTURES / 'observations.json').read_text(encoding='utf-8'))
        # Native output is -text in its local .gitattributes: no normalization.
        cls.native_bytes = (FIXTURES / 'collections.out').read_bytes()
        cls.records = contract._records(cls.native_bytes)
        # Explicit checkout transport normalization of source only.
        cls.source = (ROOT / 'integrational_tests/tests/collections.bsl').read_bytes().replace(b'\r\n', b'\n')
        cls.messages = []
        vm = Interpreter(cls.messages.append, native_target=LINUX_8_3_27_1508)
        try:
            vm.execute(cls.source.decode('utf-8-sig'))
        finally:
            vm.close()
        cls.actual_bytes = ('\n'.join(cls.messages) + '\n').encode('utf-8')

    def test_bounded_public_capture_pins_and_exact_native_bytes(self):
        self.assertEqual(set(self.native), {
            'status', 'native_run', 'native_run_attempt', 'native_run_url',
            'head_sha', 'checkout_sha', 'tree_sha', 'platform', 'contexts',
            'source_sha256', 'output_sha256', 'output_bytes',
            'server_and_managed_client_message_count', 'previous_messages',
            'record_count', 'records', 'limits',
        })
        self.assertEqual(self.native['status'], 'audited_native_capture_not_fresh_runtime_acceptance')
        self.assertEqual(self.native['native_run'], 40048537592)
        self.assertEqual(self.native['native_run_attempt'], 1)
        self.assertEqual(self.native['native_run_url'],
                         'https://github.com/Atridis/yadinassi/actions/runs/40048537592')
        self.assertEqual(self.native['head_sha'], '93553e7149dd7c10f218c3e26d025a8d1053cb46')
        self.assertEqual(self.native['checkout_sha'], '00e748d0da56ebf8b60703c5881b8e334165ff12')
        self.assertEqual(self.native['tree_sha'], 'fc76a3e050a455d3a2f185a9f19d80ab3522e293')
        self.assertEqual(self.native['platform'], 'Linux 1C 8.3.27.1508')
        self.assertEqual(self.native['contexts'], ['server', 'managed-client'])
        self.assertEqual(self.native['source_sha256'], SOURCE_SHA256)
        self.assertEqual(hashlib.sha256(self.source).hexdigest(), SOURCE_SHA256)
        self.assertEqual(self.native['output_sha256'], OUTPUT_SHA256)
        self.assertEqual(hashlib.sha256(self.native_bytes).hexdigest(), OUTPUT_SHA256)
        self.assertEqual(len(self.native_bytes), 233298)
        self.assertEqual(self.native['output_bytes'], 233298)
        self.assertEqual(self.native['server_and_managed_client_message_count'], 854)
        self.assertEqual(self.native['previous_messages'], 841)
        self.assertEqual(self.native['record_count'], 13)
        suffix = b''.join(record[1] for record in self.records[841:])
        self.assertEqual(hashlib.sha256(suffix).hexdigest(), SUFFIX_SHA256)

    def test_all_thirteen_records_and_states_come_from_real_output(self):
        self.assertEqual(len(self.native['records']), 13)
        self.assertEqual([row['label'] for row in self.native['records']],
                         [probe[0] for probe in PROBES])
        pattern = (r'(ok|error);\{"N",(\d+)\};\{"N",(\d+)\};\{"N",(\d+)\};'
                   r'\{"N",(\d+)\};\{"B",([01])\};(?:\{"N",(\d+)\}|\{"U"\})')
        for ordinal, (observed, native_record) in enumerate(
                zip(self.native['records'], self.records[841:]), 842):
            with self.subTest(ordinal=ordinal):
                self.assertEqual(set(observed), {'ordinal', 'label', 'record', 'state'})
                self.assertEqual(observed['ordinal'], ordinal)
                self.assertEqual(observed['label'], native_record[0])
                self.assertEqual(observed['record'] + '\n', native_record[1].decode('utf-8'))
                match = re.fullmatch(pattern, native_record[2].decode('utf-8'))
                self.assertIsNotNone(match)
                status, first, last, copy, count, missing, value = match.groups()
                self.assertEqual(observed['state'], dict(
                    status=status, first=int(first), last=int(last), copy=int(copy),
                    target_count=int(count), target_missing=missing == '1',
                    target_missing_value=int(value) if value is not None else None))
        self.assertEqual(self.messages[841:], [row['record'] for row in self.native['records']])

    def test_full_854_replay_accepts_only_unchanged_eight_map_allowance(self):
        self.assertEqual(len(self.messages), 854)
        self.assertEqual(contract.ELIGIBLE_LABELS, MAP_LABELS)
        self.assertEqual(contract.compare_collections(
            self.native_bytes, self.actual_bytes, hashlib.sha256(self.source).hexdigest()), {
                'status': 'equivalent', 'profile': 'typed-map-order-v1',
                'records': 854, 'byte_equal_records': 846,
                'accepted_labels': list(MAP_LABELS), 'reason': 'none',
            })
        actual_records = contract._records(self.actual_bytes)
        self.assertEqual([left[0] for left, right in zip(self.records, actual_records)
                          if left[1] != right[1]], list(MAP_LABELS))

    def test_every_exclude_state_remains_strict_and_source_bound(self):
        for label, raw, _ in self.records[841:]:
            with self.subTest(label=label):
                # A synthetic state mutation must not join the Map allowance.
                changed = re.sub(rb'\{"N",\d+\}', b'{"N",999}', raw, count=1)
                mutated = self.actual_bytes.replace(raw, changed, 1)
                self.assertNotEqual(mutated, self.actual_bytes)
                result = contract.compare_collections(self.native_bytes, mutated, SOURCE_SHA256)
                self.assertEqual((result['status'], result['reason']),
                                 ('rejected', 'ineligible_difference'))
        result = contract.compare_collections(self.native_bytes, self.actual_bytes, '0' * 64)
        self.assertEqual((result['status'], result['reason']), ('rejected', 'source_mismatch'))

    def test_thirteen_linux_observations_and_unchanged_windows_direct_default(self):
        for (_, variant, excluded, position), native in zip(PROBES, self.native['records']):
            for target in TARGETS:
                with self.subTest(label=native['label'], target=target):
                    destination, source = make_pair(variant, position)
                    before = state(destination, 'error')
                    source_before = source._items.copy()
                    target_keys = [pair.key for pair in destination]
                    expected = native['state']
                    if target != LINUX_8_3_27_1508 and variant == 'source-only':
                        expected = before
                    self.assertEqual(invoke(destination, source, excluded, target), expected)
                    self.assertEqual(source._items, source_before)
                    self.assertEqual([pair.key for pair in destination], target_keys)
        self.assertEqual(current_native_target(), WINDOWS_8_3_27_2342)

    def test_fixed_source_and_target_keep_unmeasured_guards(self):
        for (_, variant, excluded, position), native in zip(PROBES, self.native['records']):
            for target, fixed_target in product(TARGETS, (False, True)):
                with self.subTest(label=native['label'], target=target, fixed_target=fixed_target):
                    destination, source = make_pair(variant, position)
                    if fixed_target:
                        destination = BSLFixedStructure(destination)
                    else:
                        source = BSLFixedStructure(source)
                    before = state(destination, 'error')
                    expected = before if fixed_target or variant == 'source-only' else native['state']
                    self.assertEqual(invoke(destination, source, excluded, target), expected)

    def assert_upfront_guard(self, destination, source, excluded, include=None):
        before = destination._items.copy()
        source_before = source._items.copy()
        with target_context(LINUX_8_3_27_1508), self.assertRaises((TypeError, ValueError)):
            fill_property_values(destination, source, include, excluded)
        self.assertEqual(destination._items, before)
        self.assertEqual(source._items, source_before)
        self.assertEqual(current_native_target(), WINDOWS_8_3_27_2342)

    def test_entire_exclude_list_validates_before_any_partial_write(self):
        malformed = ('', ' ', '\t', '\u00a0', ' First', 'First ',
                     '\tFirst', 'First\n', '\u2003First', 'bad-name', '1Name')
        for bad, first in product(malformed, (False, True)):
            excluded = bad + ',Missing' if first else 'Missing,' + bad
            with self.subTest(excluded=excluded):
                self.assert_upfront_guard(*make_pair(), excluded)
        for excluded in ('', ',', 'Missing,,First', 'First,,Missing', 1, True, BSLArray()):
            with self.subTest(excluded=excluded):
                self.assert_upfront_guard(*make_pair(), excluded)

    def test_dual_lists_remain_upfront_guards(self):
        for include, exclude in product(('', 'First', 'Missing', 1), ('Missing', 'First')):
            with self.subTest(include=include, exclude=exclude):
                self.assert_upfront_guard(*make_pair(), exclude, include)

    def test_missing_from_source_prevalidates_before_deferred_target_absence(self):
        for target_has_absent, first in product((False, True), (False, True)):
            destination, source = make_pair()
            if target_has_absent:
                destination.insert('Absent', 7)
            excluded = 'Absent,Missing' if first else 'Missing,Absent'
            with self.subTest(target_has_absent=target_has_absent, excluded=excluded):
                self.assert_upfront_guard(destination, source, excluded)
        for variant in ('target-only', 'neither'):
            self.assert_upfront_guard(*make_pair(variant), 'Missing')

    def test_mixed_unmeasured_source_only_shapes_remain_upfront_guards(self):
        # Guard coverage, not extrapolated native behavior for these combinations.
        for excluded in ('Missing,Missing', 'Missing,mISSING', 'mISSING,First,Missing'):
            with self.subTest(excluded=excluded):
                self.assert_upfront_guard(*make_pair(), excluded)
        for excluded, position in product(('Missing', 'Missing,Extra', 'Extra,Missing'),
                                          ('first', 'last')):
            destination, source = make_pair()
            if position == 'first':
                extended = BSLStructure('Extra', 50)
                for item in source:
                    extended.insert(item.key, item.value)
                source = extended
            else:
                source.insert('Extra', 50)
            with self.subTest(excluded=excluded, position=position):
                self.assert_upfront_guard(destination, source, excluded)

    def test_valid_without_deferred_names_keeps_existing_copy_and_exclusions(self):
        for target, excluded in product(TARGETS, (None, 'First', 'First,FIRST')):
            destination, source = make_pair()
            with self.subTest(target=target, excluded=excluded):
                result = invoke(destination, source, excluded, target)
                self.assertEqual((result['status'], result['first'], result['last'], result['copy']),
                                 ('ok', 10 if excluded is None else 1, 20, 30))
                self.assertFalse(destination.property('Missing'))

    def test_partial_write_preserves_target_aliases_spelling_references_and_order(self):
        # Equivalent local constructor state, not a new native observation.
        destination = BSLStructure('COPY,LAST,FIRST,Keep', 3, 2, 1, 9)
        shared = BSLArray()
        source = BSLStructure('first,Missing,last,copy', shared, 40, None, 30)
        alias = destination
        original_source = source._items.copy()
        original_version = destination._version
        with target_context(LINUX_8_3_27_1508), self.assertRaises(ValueError):
            fill_property_values(destination, source, None, 'mISSING')
        self.assertIs(destination, alias)
        self.assertIs(destination.get('FIRST'), shared)
        self.assertEqual([item.key for item in destination], ['COPY', 'LAST', 'FIRST', 'Keep'])
        self.assertEqual([destination.get(name) for name in ('COPY', 'LAST', 'Keep')], [3, 2, 9])
        self.assertEqual(destination._version, original_version)
        self.assertEqual(source._items, original_source)
        alias.get('FIRST').add(7)
        self.assertEqual(source.get('first').items, [7])
        self.assertFalse(destination.property('Missing'))

    def test_successful_valid_exclusions_preserve_undefined_and_same_object(self):
        for target in TARGETS:
            shared = BSLArray()
            source = BSLStructure('First,Last,Copy', shared, None, 30)
            destination = BSLStructure('FIRST,LAST,COPY', 1, 2, 3)
            self.assertEqual(invoke(destination, source, 'Copy', target)['status'], 'ok')
            self.assertIs(destination.get('First'), shared)
            self.assertIsNone(destination.get('Last'))
            self.assertEqual(destination.get('Copy'), 3)
            before = destination._items.copy()
            self.assertEqual(invoke(destination, destination, 'First', target)['status'], 'ok')
            self.assertEqual(destination._items, before)

    def test_aliases_report_caught_or_escaping_errors_and_restore_target_context(self):
        for alias, caught in product(('FillPropertyValues', 'ЗаполнитьЗначенияСвойств'),
                                     (False, True)):
            vm = Interpreter(native_target=LINUX_8_3_27_1508)
            self.addCleanup(vm.close)
            vm.variables['target'], vm.variables['source'] = make_pair(position='between')
            call = f'{alias}(target, source, Undefined, "Missing");'
            with self.subTest(alias=alias, caught=caught):
                if caught:
                    vm.execute('Try ' + call + ' Except caught=True; EndTry;')
                    self.assertIs(vm.variables['caught'], True)
                else:
                    with self.assertRaises(BSLRuntimeError) as error:
                        vm.execute(call, source='fill-exclude.bsl')
                    self.assertEqual(error.exception.source, 'fill-exclude.bsl')
                    self.assertEqual(error.exception.message, MISSING_GUARD)
                self.assertEqual(state(vm.variables['target'], 'error'), self.native['records'][-1]['state'])
                self.assertEqual(current_native_target(), WINDOWS_8_3_27_2342)
                self.assertEqual(vm._context_stack, ['client'])
                self.assertEqual(vm._module_context_stack, [True])
                self.assertIsNone(vm.locals)
                vm.execute(f'{alias}(target, source);')
                self.assertEqual([vm.variables['target'].get(name) for name in ('First', 'Last', 'Copy')],
                                 [10, 20, 30])
                self.assertEqual(current_native_target(), WINDOWS_8_3_27_2342)

    def test_nested_native_target_context_restores_after_direct_error(self):
        with target_context(LINUX_8_3_27_1508):
            with self.assertRaises(ValueError):
                with target_context(WINDOWS_8_3_27_2342):
                    destination, source = make_pair()
                    fill_property_values(destination, source, None, 'Missing')
            self.assertEqual(current_native_target(), LINUX_8_3_27_1508)
            self.assertEqual(state(destination, 'error')['first'], 1)
            with self.assertRaises(ValueError):
                fill_property_values(destination, source, None, 'Missing')
            self.assertEqual(state(destination, 'error')['first'], 10)
        self.assertEqual(current_native_target(), WINDOWS_8_3_27_2342)


