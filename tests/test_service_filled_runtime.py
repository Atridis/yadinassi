ALIASES = ('ЗначениеЗаполнено', 'ValueIsFilled')


def forbidden_hook(*args, **kwargs):
    raise AssertionError('filled-value dispatch invoked a host hook')


class HostileMeta(type):
    __eq__ = __ne__ = __hash__ = forbidden_hook


class Hostile(metaclass=HostileMeta):
    __bool__ = __len__ = __iter__ = __getattribute__ = forbidden_hook
    __eq__ = __ne__ = __hash__ = __str__ = __repr__ = forbidden_hook


def changed(value, field, replacement):
    """Build an isolated invalid host state without invoking a field's hooks."""
    object.__setattr__(value, field, replacement)
    return value


class ServiceFilledNativeRuntimeTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.native = json.loads(
            (ROOT / 'tests/fixtures/service_filled_linux.json').read_text(encoding='utf-8'))
        cls.expected = {}
        for record in cls.native['records'][:-1]:
            name, payload = record.split(': ', 1)
            cls.expected[name.removeprefix('types-extra.service-filled.')] = {
                '[value={"B",0}]': False,
                '[value={"B",1}]': True,
            }[payload]

    def setUp(self):
        self.vm = Interpreter(lambda _: None)

    def test_native_provenance_source_hash_and_complete_402_message_suffix(self):
        self.assertEqual(self.native['native_run'], 39796997071)
        self.assertEqual(self.native['native_run_url'],
                         'https://github.com/Atridis/yadinassi/actions/runs/39796997071')
        self.assertEqual(self.native['platform'], 'Linux 1C 8.3.27.1508')
        self.assertEqual(self.native['contexts'], ['server', 'managed-client'])
        source = (ROOT / 'integrational_tests/tests/values.bsl').read_bytes()
        self.assertEqual(hashlib.sha256(source).hexdigest(), self.native['source_sha256'])
        output = []
        Interpreter(output.append).execute(source.decode('utf-8'))
        self.assertEqual(self.native['previous_messages'], 377)
        self.assertEqual(self.native['server_and_managed_client_message_count'], 402)
        self.assertEqual(len(output), 402)
        self.assertEqual(output[377:], self.native['records'])
        self.assertEqual(len(self.native['records']), 25)
        self.assertEqual(self.native['records'][-1],
                         'types-extra.service-filled.checkpoint.complete: [ok]')
        self.assertEqual(list(self.expected),
                         [f'{label}.{language}' for label, _ in CASES
                          for language in ('ru', 'en')])

    def test_every_native_case_via_both_aliases_and_direct_runtime_value(self):
        for label, expression in CASES:
            with self.subTest(case=label):
                value = self.vm.execute(expression)
                self.assertIs(value_is_filled(value), self.expected[label + '.en'])
                for language, alias in zip(('ru', 'en'), ALIASES):
                    expected = self.expected[f'{label}.{language}']
                    self.assertIs(self.vm.execute(f'{alias}({expression})'), expected)
                    self.vm.variables['service'] = value
                    self.assertIs(self.vm.execute(f'{alias}(service)'), expected)
                    self.assertIs(self.vm.execute(
                        f'(TypeOf({alias}(service)) = Type("Boolean"))'), True)
                    self.assertEqual(self.vm.execute(
                        f'ValueToStringInternal({alias}(service))'),
                        '{"B",' + str(int(expected)) + '}')

    def test_alias_case_and_russian_service_spellings(self):
        for label, expression in (
            ('type.number', 'Тип("Число")'),
            ('type.string', 'Тип("Строка")'),
            ('round.down', 'РежимОкругления.Окр15как10'),
            ('round.up', 'РежимОкругления.Окр15как20'),
            ('round.namespace', 'РежимОкругления'),
            ('description.empty', 'Новый ОписаниеТипов'),
            ('description.number', 'Новый ОписаниеТипов("Число")'),
            ('description.string', 'Новый ОписаниеТипов("Строка")'),
            ('number.default', 'Новый КвалификаторыЧисла'),
            ('number.qualified', 'Новый КвалификаторыЧисла(10,2,ДопустимыйЗнак.Любой)'),
            ('string.default', 'Новый КвалификаторыСтроки'),
            ('string.fixed4', 'Новый КвалификаторыСтроки(4,ДопустимаяДлина.Фиксированная)'),
        ):
            for alias in ('зНаЧеНиЕзАпОлНеНо', 'vAlUeIsFiLlEd'):
                with self.subTest(case=label, alias=alias):
                    self.assertIs(self.vm.execute(f'{alias}({expression})'),
                                  self.expected[label + '.en'])

    def test_reconstructed_and_normalized_qualifiers_use_state_not_identity(self):
        # These constructor equivalences are local behavior already supported;
        # the filled result comes from the corresponding measured final state.
        for label, expressions in (
            ('number.default', ('New NumberQualifiers(0,0,AllowedSign.Any)',
                                'New NumberQualifiers(0,9)',
                                'New NumberQualifiers(-1,0)')),
            ('number.qualified', ('New NumberQualifiers(10,2)',
                                  'New NumberQualifiers("10","2",AllowedSign.Any)',
                                  'New NumberQualifiers(10.9,2.9)')),
            ('string.default', ('New StringQualifiers(0,AllowedLength.Variable)',
                                'New StringQualifiers(0,AllowedLength.Fixed)',
                                'New StringQualifiers(-1,AllowedLength.Fixed)')),
            ('string.fixed4', ('New StringQualifiers("4",AllowedLength.Fixed)',
                               'New StringQualifiers(4.9,AllowedLength.Fixed)')),
        ):
            for expression in expressions:
                with self.subTest(case=label, expression=expression):
                    first, second = (self.vm.execute(expression) for _ in range(2))
                    self.assertIsNot(first, second)
                    for value in (first, second):
                        self.assertIs(value_is_filled(value), self.expected[label + '.en'])

    def test_reconstructed_descriptions_use_normalized_types_and_default_qualifiers(self):
        for label, type_name, names in (
            ('description.empty', None, ('', 'Undefined', 'Undefined,Undefined')),
            ('description.number', BSLType.NUMBER, ('Number', 'Число', ' number,Number,Undefined ')),
            ('description.string', BSLType.STRING, ('String', 'Строка', ' string,String,Undefined ')),
        ):
            array = BSLArray()
            if type_name is not None:
                array.add(type_name)
            array.add(BSLType.UNDEFINED)
            descriptors = [BSLTypeDescription(name) for name in names]
            descriptors += [BSLTypeDescription(array), BSLTypeDescription(descriptors[0]),
                            BSLTypeDescription(names[0], BSLNumberQualifiers(),
                                               BSLStringQualifiers(), BSLDateQualifiers(),
                                               BSLBinaryDataQualifiers())]
            for index, value in enumerate(descriptors):
                with self.subTest(case=label, variant=index):
                    self.assertIs(value_is_filled(value), self.expected[label + '.en'])

    def test_service_checks_do_not_depend_on_decimal_precision_or_traps(self):
        values = [(self.vm.execute(expression), self.expected[label + '.en'])
                  for label, expression in CASES]
        with localcontext() as context:
            context.prec = 1
            context.traps[Inexact] = context.traps[Rounded] = True
            context.clear_flags()
            for value, expected in values:
                self.assertIs(value_is_filled(value), expected)
            self.assertFalse(any(context.flags.values()))


class ServiceFilledBoundaryTests(unittest.TestCase):
    def assert_unsupported(self, value):
        with self.assertRaisesRegex(TypeError, UNSUPPORTED):
            value_is_filled(value)

    def test_all_unmeasured_type_descriptors_and_other_service_namespaces_fail_closed(self):
        for kind in BSLType:
            if kind is not BSLType.NUMBER and kind is not BSLType.STRING:
                with self.subTest(kind=kind.name):
                    self.assert_unsupported(kind)
        values = [BSLDateQualifiers(), BSLDateQualifiers(BSLDateFractions.DATE),
                  BSLBinaryDataQualifiers(), BSLBinaryDataQualifiers(4),
                  ALLOWED_SIGNS, ALLOWED_LENGTHS, DATE_FRACTIONS,
                  *BSLAllowedSign, *BSLAllowedLength, *BSLDateFractions]
        for index, value in enumerate(values):
            with self.subTest(index=index):
                self.assert_unsupported(value)

    def test_unmeasured_qualifier_states_fail_closed_not_just_nonzero(self):
        values = [BSLNumberQualifiers(1), BSLNumberQualifiers(10),
                  BSLNumberQualifiers(10,1), BSLNumberQualifiers(11,2),
                  BSLNumberQualifiers(10,2,BSLAllowedSign.NONNEGATIVE),
                  BSLNumberQualifiers(0,0,BSLAllowedSign.NONNEGATIVE),
                  BSLStringQualifiers(4), BSLStringQualifiers(1),
                  BSLStringQualifiers(3,BSLAllowedLength.FIXED),
                  BSLStringQualifiers(5,BSLAllowedLength.FIXED)]
        for index, value in enumerate(values):
            with self.subTest(index=index):
                self.assert_unsupported(value)

    def test_exact_class_without_measured_enum_identity_is_not_accepted(self):
        for kind in (BSLType, BSLRoundMode):
            with self.subTest(kind=kind.__name__):
                self.assert_unsupported(object.__new__(kind))

    def test_composite_unmeasured_and_qualified_descriptions_fail_closed(self):
        values = [BSLTypeDescription(name) for name in
                  ('Boolean', 'Date', 'Null', 'Number,String', 'Number,Boolean',
                   'Number,Date', 'String,Boolean,Date,Number')]
        values += [BSLTypeDescription('Number', BSLNumberQualifiers(10,2)),
                   BSLTypeDescription('Number', BSLNumberQualifiers(0,0,BSLAllowedSign.NONNEGATIVE)),
                   BSLTypeDescription('String', None, BSLStringQualifiers(4,BSLAllowedLength.FIXED)),
                   BSLTypeDescription('Date', None, None, BSLDateQualifiers(BSLDateFractions.DATE))]
        for index, value in enumerate(values):
            with self.subTest(index=index):
                self.assert_unsupported(value)

    def test_known_round_namespace_uses_identity_without_access_iteration_or_truth(self):
        with ExitStack() as stack:
            for method in ('__getattribute__', '__bool__', '__len__', '__iter__',
                           '__eq__', '__ne__', '__hash__', '__str__', '__repr__'):
                stack.enter_context(patch.object(BSLRoundModes, method, forbidden_hook, create=True))
            self.assertIs(value_is_filled(ROUND_MODES), True)
            self.assert_unsupported(BSLRoundModes())

    def test_measured_service_values_do_not_use_equality_hash_or_generic_truthiness(self):
        values = [(BSLType.NUMBER, True), (BSLType.STRING, True),
                  (BSLRoundMode.ROUND15_AS10, True), (BSLRoundMode.ROUND15_AS20, True),
                  (BSLNumberQualifiers(), False), (BSLNumberQualifiers(10,2), True),
                  (BSLStringQualifiers(), False),
                  (BSLStringQualifiers(4,BSLAllowedLength.FIXED), True),
                  (BSLTypeDescription(), False), (BSLTypeDescription('Number'), True),
                  (BSLTypeDescription('String'), True)]
        with ExitStack() as stack:
            for kind in (BSLType, BSLRoundMode, BSLNumberQualifiers,
                         BSLStringQualifiers, BSLTypeDescription):
                for method in ('__bool__', '__len__', '__iter__', '__eq__', '__ne__', '__hash__'):
                    stack.enter_context(patch.object(kind, method, forbidden_hook, create=True))
            for value, expected in values:
                self.assertIs(value_is_filled(value), expected)

    def test_hostile_metaclasses_and_every_service_subclass_are_rejected_before_attribute_access(self):
        self.assert_unsupported(Hostile())
        for base in (BSLNumberQualifiers, BSLStringQualifiers, BSLTypeDescription,
                     BSLRoundModes, BSLDateQualifiers, BSLBinaryDataQualifiers):
            with self.subTest(base=base.__name__):
                subclass = HostileMeta('HostService', (base,), {
                    method: forbidden_hook for method in
                    ('__getattribute__', '__bool__', '__len__', '__iter__', '__eq__',
                     '__ne__', '__hash__', '__str__', '__repr__')})
                # Leave all fields absent: exact-type rejection must happen first.
                self.assert_unsupported(object.__new__(subclass))

    def test_invalid_numeric_qualifier_fields_are_not_coerced_or_compared(self):
        class HostDecimal(Decimal):
            __getattribute__ = __eq__ = __bool__ = forbidden_hook

        invalid = [Hostile(), HostDecimal(0), 0, '0', False,
                   *(Decimal(text) for text in ('NaN', 'sNaN', 'Infinity', '-Infinity'))]
        for index, replacement in enumerate(invalid):
            for constructor, field in ((BSLNumberQualifiers, 'digits'),
                                       (BSLNumberQualifiers, 'fraction_digits'),
                                       (BSLStringQualifiers, 'length')):
                with self.subTest(index=index, field=field):
                    self.assert_unsupported(changed(constructor(), field, replacement))
        for constructor, field in ((BSLNumberQualifiers, 'allowed_sign'),
                                   (BSLStringQualifiers, 'allowed_length')):
            self.assert_unsupported(changed(constructor(), field, Hostile()))

    def test_description_fields_are_validated_without_host_equality_or_iteration(self):
        class HostTuple(tuple):
            __len__ = __iter__ = __getitem__ = __eq__ = forbidden_hook

        for field in ('number_qualifiers', 'string_qualifiers',
                      'date_qualifiers', 'binary_data_qualifiers', 'types'):
            with self.subTest(field=field):
                self.assert_unsupported(changed(BSLTypeDescription('Number'), field, Hostile()))
        for types in ([], [BSLType.NUMBER], HostTuple((BSLType.NUMBER,)), (Hostile(),)):
            self.assert_unsupported(changed(BSLTypeDescription('Number'), 'types', types))
        invalid_qualifiers = [
            ('number_qualifiers', changed(BSLNumberQualifiers(), 'digits', Hostile())),
            ('string_qualifiers', changed(BSLStringQualifiers(), 'length', Hostile())),
            ('date_qualifiers', changed(BSLDateQualifiers(), 'date_fractions', Hostile())),
            ('date_qualifiers', BSLDateQualifiers(BSLDateFractions.TIME)),
            ('binary_data_qualifiers', changed(BSLBinaryDataQualifiers(), 'length', Hostile())),
            ('binary_data_qualifiers', changed(BSLBinaryDataQualifiers(), 'length', Decimal('sNaN'))),
            ('binary_data_qualifiers', changed(BSLBinaryDataQualifiers(), 'allowed_length', Hostile())),
            ('binary_data_qualifiers', BSLBinaryDataQualifiers(4,BSLAllowedLength.FIXED)),
        ]
        for index, (field, replacement) in enumerate(invalid_qualifiers):
            with self.subTest(index=index, field=field):
                self.assert_unsupported(changed(BSLTypeDescription('Number'), field, replacement))

    def test_runtime_errors_preserve_assignment_are_catchable_and_allow_recovery(self):
        vm = Interpreter(lambda _: None)
        for expression in ('Type("Boolean")', 'AllowedSign.Any', 'AllowedLength.Fixed',
                           'DateFractions.DateTime', 'New DateQualifiers', 'New BinaryDataQualifiers',
                           'New NumberQualifiers(5)', 'New NumberQualifiers(10,2,AllowedSign.Nonnegative)',
                           'New StringQualifiers(4)', 'New TypeDescription("Number,String")',
                           'New TypeDescription("Number",New NumberQualifiers(10,2))',
                           'New TypeDescription("String",Undefined,New StringQualifiers(4,AllowedLength.Fixed))'):
            # Establish that it is ValueIsFilled, not construction, that fails.
            vm.execute(expression)
            for alias in ALIASES:
                with self.subTest(expression=expression, alias=alias):
                    vm.execute('saved = "unchanged"')
                    with self.assertRaisesRegex(BSLError, UNSUPPORTED):
                        vm.execute(f'saved = {alias}({expression})')
                    self.assertEqual(vm.execute('saved'), 'unchanged')
                    self.assertIs(vm.execute(
                        f'caught = False; Try saved = {alias}({expression}); '
                        'Except caught = True; EndTry; caught'), True)
                    self.assertEqual(vm.execute('saved'), 'unchanged')
                    self.assertIs(vm.execute(f'{alias}(New NumberQualifiers)'), False)
                    self.assertIs(vm.execute(f'{alias}(RoundMode.Round15as10)'), True)


