LANE = 'owned_metadata_catalog_public_runtime_v1'
DEPENDENCIES = {'prompt-toolkit':'3.0.53', 'pyuca':'1.2', 'tzdata':'2026.5', 'wcwidth':'0.8.2'}
PACKAGES = {'prompt-toolkit':'prompt_toolkit', 'pyuca':'pyuca', 'tzdata':'tzdata', 'wcwidth':'wcwidth'}
MANIFEST = 'runtime_bundle_manifest.json'
PRIVATE_INSTALLER_FILES = frozenset(('direct_url.json', 'INSTALLER', 'REQUESTED'))
MAX_FILE = 4 * 1024 * 1024
MAX_TOTAL = 32 * 1024 * 1024
MAX_FILES = 2048
MAX_MANIFEST = 512 * 1024
MAX_RECORD_BYTES = 512 * 1024
MAX_RECORD_ROWS = 4096
MAX_RECORD_LINE = 2048
MAX_METADATA_BYTES = 256 * 1024
MAX_DEPTH = 32
MAX_RUNTIME_DIRECTORIES = 256
MAX_STAGE_DIRECTORIES = 4096
SOURCE_FILES = {**base.SOURCE_FILES,
    **{'scripts/native_1c_db_oracle/' + name:name for name in (
        'metadata_catalog_runtime_inputs.py', 'metadata_catalog_runtime_readback.py',
        'metadata_catalog_runtime_acquisition.py', 'metadata_catalog_runtime_run.py',
        'metadata_catalog_runtime_report.py')},
    'scripts/native_1c_metadata_catalog_runtime_oracle.py':'metadata_runtime_host.py',
    MANIFEST:MANIFEST}
PROVENANCE_FILES = ('pyproject.toml', 'scripts/native_1c_full_host.py', 'scripts/native_1c_smoke.py',
    'scripts/native_1c_map_contract.py', 'scripts/native_1c_tree_load_contract.py',
    'scripts/native_1c_tree_move_contract.py', 'scripts/native_1c_tree_total_contract.py',
    'scripts/native_async_comparison.py', 'scripts/native_infobase_fixture.py')


def _json(value):
    return json.dumps(value, ensure_ascii=True, sort_keys=True, separators=(',', ':'), allow_nan=False).encode('ascii')


def _name(name):
    require(type(name) is str and 0 < len(name) <= 512 and '\\' not in name
            and all(ord(c) >= 32 and ord(c) != 127 for c in name), 'invalid_input')
    path = PurePosixPath(name)
    require(not path.is_absolute() and path.as_posix() == name
        and len(path.parts) <= MAX_DEPTH
        and all(p not in ('', '.', '..') for p in path.parts), 'invalid_input')
    return path


def _read(path, maximum=MAX_FILE):
    """Stable regular-file bytes; allow empty __init__.py and dependency data."""
    try:
        require(not any(p.is_symlink() for p in (path, *path.parents)), 'invalid_input')
        initial = path.lstat()
        require(stat.S_ISREG(initial.st_mode) and initial.st_nlink == 1
                and 0 <= initial.st_size <= maximum, 'invalid_input')
        with path.open('rb') as stream:
            before = os.fstat(stream.fileno()); raw = stream.read(maximum + 1); after = os.fstat(stream.fileno())
        key = lambda s:(s.st_dev,s.st_ino,s.st_size,s.st_mtime_ns,s.st_ctime_ns)
        require(key(initial) == key(before) == key(after) and len(raw) == initial.st_size, 'invalid_input')
        return raw
    except OSError:
        raise OracleError('invalid_input') from None


def _walk(root, *, max_files, max_directories, skip_cache=False):
    """Count each entry before descending; never materialize an unbounded tree.

    Yield directories before descent, allowing the staged consumer to reject an
    unknown directory without opening it. Source caches are never traversed.
    """
    files = directories = 0
    def visit(directory, depth):
        nonlocal files, directories
        require(depth <= MAX_DEPTH, 'artifact_limit')
        try:
            with os.scandir(directory) as entries:
                for entry in entries:
                    require(not entry.is_symlink(), 'invalid_input')
                    is_directory = entry.is_dir(follow_symlinks=False)
                    if is_directory and skip_cache and entry.name == '__pycache__':
                        continue
                    require(depth <= MAX_DEPTH, 'artifact_limit')
                    if is_directory:
                        directories += 1
                        require(directories <= max_directories, 'artifact_limit')
                    else:
                        files += 1
                        require(files <= max_files, 'artifact_limit')
                    path = Path(entry.path)
                    yield path, is_directory
                    if is_directory:
                        yield from visit(path, depth + 1)
        except OSError:
            raise OracleError('invalid_input') from None
    yield from visit(root, 1)


def _source_runtime(root):
    files = {}
    total = 0
    package = root / 'yadinassi'
    require(package.is_dir() and not package.is_symlink(), 'invalid_input')
    for path, is_directory in _walk(package, max_files=512,
            max_directories=MAX_RUNTIME_DIRECTORIES, skip_cache=True):
        _name(path.relative_to(root).as_posix())
        if is_directory: continue
        require(path.suffix in ('.py', '.txt'), 'invalid_input')
        raw = _read(path)
        total += len(raw)
        require(total <= MAX_TOTAL, 'artifact_limit')
        files[path.relative_to(root).as_posix()] = raw
    require(0 < len(files) <= 512 - len(PROVENANCE_FILES), 'artifact_limit')
    for name in PROVENANCE_FILES:
        raw = _read(root / name)
        total += len(raw)
        require(total <= MAX_TOTAL, 'artifact_limit')
        files[name] = raw
    files = dict(sorted(files.items()))
    # Reuse the exact full-host dependency convention without importing its host driver.
    text = files['scripts/native_1c_full_host.py'].decode('utf-8')
    import ast
    assignments = [n for n in ast.parse(text).body if isinstance(n, ast.Assign)
                   and any(isinstance(t, ast.Name) and t.id == 'DEPENDENCIES' for t in n.targets)]
    require(len(assignments) == 1 and ast.literal_eval(assignments[0].value) == DEPENDENCIES,
            'provenance_mismatch')
    project = files['pyproject.toml'].decode('utf-8')
    for name in ('prompt-toolkit', 'pyuca', 'tzdata'):
        require('"' + name + '==' + DEPENDENCIES[name] + '"' in project, 'provenance_mismatch')
    return files


def _dependencies():
    files = {}
    total = rows = 0
    for name, version in DEPENDENCIES.items():
        try: distribution = importlib.metadata.distribution(name)
        except importlib.metadata.PackageNotFoundError: raise OracleError('invalid_input') from None
        package = PACKAGES[name]
        distinfo = package + '-' + version + '.dist-info'
        # Locate only the fixed, trusted installation root. Do not ask stdlib
        # for distribution.files: it eagerly materializes and stats RECORD paths.
        installed = Path(distribution.locate_file(''))
        metadata = BytesParser().parsebytes(_read(installed / distinfo / 'METADATA', MAX_METADATA_BYTES),
                                           headersonly=True)
        names = metadata.get_all('Name', [])
        require(len(names) == 1 and re.fullmatch(r'[A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?', names[0])
                and re.sub(r'[-_.]+', '-', names[0]).lower() == name
                and metadata.get_all('Version') == [version], 'provenance_mismatch')
        record_name = distinfo + '/RECORD'
        record = _read(installed / record_name, MAX_RECORD_BYTES)
        try: lines = io.StringIO(record.decode('utf-8'))
        except UnicodeError: raise OracleError('invalid_input') from None
        seen = set()
        for line in lines:
            # Count physical records, including every cache/private/empty row,
            # before CSV decoding, path handling or any payload filesystem call.
            rows += 1
            require(rows <= MAX_RECORD_ROWS and len(line) <= MAX_RECORD_LINE, 'artifact_limit')
            try: fields = next(csv.reader((line,), strict=True))
            except (csv.Error, StopIteration): raise OracleError('invalid_input') from None
            require(len(fields) == 3, 'invalid_input')
            relative, recorded_hash, recorded_size = fields
            path = _name(relative)
            require(path.suffix.casefold() != '.pth' and path.parts[0] in (package, distinfo)
                    and len(path.parts) >= 2 and relative not in seen, 'invalid_input')
            seen.add(relative)
            require(recorded_hash == '' or re.fullmatch(r'sha256=[A-Za-z0-9_-]{43}', recorded_hash),
                    'invalid_input')
            require(recorded_size == '' or re.fullmatch(r'0|[1-9][0-9]{0,9}', recorded_size),
                    'invalid_input')
            if '__pycache__' in path.parts or path.suffix == '.pyc': continue
            if path.parts[0] == distinfo and path.name in PRIVATE_INSTALLER_FILES: continue
            require(len(files) < MAX_FILES, 'artifact_limit')
            # All relative-path checks precede constructing or inspecting this path.
            raw = record if relative == record_name else _read(installed / relative)
            if recorded_hash:
                expected = base64.urlsafe_b64encode(hashlib.sha256(raw).digest()).rstrip(b'=').decode('ascii')
                require(recorded_hash == 'sha256=' + expected and recorded_size != ''
                        and int(recorded_size) == len(raw), 'provenance_mismatch')
            else:
                require(relative == record_name and recorded_size == '', 'provenance_mismatch')
            target = 'dependencies/' + relative
            require(target not in files, 'invalid_input')
            total += len(raw)
            require(total <= MAX_TOTAL, 'artifact_limit')
            files[target] = raw
        require(record_name in seen and distinfo + '/METADATA' in seen, 'invalid_input')
    return files


def _bundle(root):
    runtime = _source_runtime(root)
    files = {**runtime, **_dependencies()}
    require(len(files) <= MAX_FILES and sum(map(len, files.values())) <= MAX_TOTAL, 'artifact_limit')
    manifest = {'schema':1, 'dependencies':DEPENDENCIES,
                'runtime_sources':sorted(runtime),
                'files':{name:{'bytes':len(raw), 'sha256':hashlib.sha256(raw).hexdigest()}
                         for name,raw in sorted(files.items())}}
    raw = _json(manifest)
    require(len(raw) <= MAX_MANIFEST, 'artifact_limit')
    return raw, files


def source_hashes(root):
    root = Path(root)
    manifest, _ = _bundle(root)
    return {name:hashlib.sha256(manifest if name == MANIFEST else _read(root / name)).hexdigest()
            for name in SOURCE_FILES}


def _manifest(root):
    raw = _read(root / MANIFEST, MAX_MANIFEST)
    try: value = json.loads(raw.decode('ascii'), object_pairs_hook=__import__('protocol').unique)
    except (ValueError, UnicodeError, RecursionError): raise OracleError('invalid_input') from None
    exact(value, ('schema', 'dependencies', 'runtime_sources', 'files'))
    require(type(value['schema']) is int and value['schema'] == 1
            and value['dependencies'] == DEPENDENCIES, 'provenance_mismatch')
    files = value['files']; sources = value['runtime_sources']
    require(type(files) is dict and 0 < len(files) <= MAX_FILES
            and type(sources) is list and 0 < len(sources) <= 512, 'invalid_input')
    require(all(type(s) is str for s in sources) and sources == sorted(set(sources)), 'invalid_input')
    require(set(PROVENANCE_FILES) <= set(sources), 'invalid_input')
    for name in sources:
        path = _name(name)
        require(name in PROVENANCE_FILES or
                path.parts[0] == 'yadinassi' and path.suffix in ('.py', '.txt')
                and '__pycache__' not in path.parts, 'invalid_input')
    total = 0
    for name, info in files.items():
        path = _name(name); exact(info, ('bytes', 'sha256'))
        require(path.suffix.casefold() != '.pth' and not
                (any(part.endswith('.dist-info') for part in path.parts)
                 and path.name in PRIVATE_INSTALLER_FILES), 'invalid_input')
        require(type(info['bytes']) is int and 0 <= info['bytes'] <= MAX_FILE
            and __import__('protocol').digest(info['sha256']), 'invalid_input')
        if name not in sources:
            require(len(path.parts) >= 3 and path.parts[0] == 'dependencies'
                and path.parts[1] in ({*PACKAGES.values()} |
                    {PACKAGES[n] + '-' + v + '.dist-info' for n,v in DEPENDENCIES.items()}), 'invalid_input')
        total += info['bytes']
    require(set(sources) <= set(files) and total <= MAX_TOTAL, 'artifact_limit')
    require(_json(value) == raw, 'invalid_input')
    return raw, value


def staged_hashes(root):
    root = Path(root)
    raw, manifest = _manifest(root)
    allowed = set(SOURCE_FILES.values()) | set(manifest['files']) | {'invocation.json'}
    # Source-provenance helpers occur in the manifest and are kept at their repo paths.
    directories = {p.as_posix() for name in allowed for p in PurePosixPath(name).parents if str(p) != '.'}
    require(len(directories) <= MAX_STAGE_DIRECTORIES, 'artifact_limit')
    actual = set()
    for path, is_directory in _walk(root, max_files=len(allowed),
            max_directories=len(directories)):
        name = path.relative_to(root).as_posix()
        if is_directory:
            require(name in directories, 'invalid_input')
        else:
            require(name in allowed, 'invalid_input')
            actual.add(name)
    require(actual == allowed, 'invalid_input')
    for name, info in manifest['files'].items():
        data = _read(root / name)
        require(len(data) == info['bytes'] and hashlib.sha256(data).hexdigest() == info['sha256'],
                'provenance_mismatch')
    return {name:hashlib.sha256(raw if name == MANIFEST else _read(root / target)).hexdigest()
            for name,target in SOURCE_FILES.items()}


def verify_inputs(root, nonce):
    root = Path(root)
    require(type(nonce) is str and re.fullmatch('[0-9a-f]{32}', nonce) is not None, 'invalid_input')
    value = decode(_read(root / 'invocation.json', 32768))
    exact(value, ('schema','lane','nonce','provenance'))
    require(type(value['schema']) is int and value['schema'] == 1 and value['lane'] == LANE
            and value['nonce'] == nonce, 'provenance_mismatch')
    provenance = value['provenance']; validate_provenance(provenance, provenance)
    require(provenance['image'] == IMAGE and provenance['platform'] == 'linux/amd64'
            and provenance['locale'] == 'ru_RU.UTF-8' and provenance['timezone'] == 'Etc/UTC'
            and provenance['actual_version'] is None
            and provenance['sources'] == staged_hashes(root), 'provenance_mismatch')
    return provenance


def stage_inputs(root, destination, nonce, provenance):
    root, destination = Path(root), Path(destination)
    require(not destination.exists() and not destination.is_symlink(), 'stale_evidence')
    manifest, bundled = _bundle(root)
    sources = {target:manifest if source == MANIFEST else _read(root / source)
               for source,target in SOURCE_FILES.items()}
    require({source:hashlib.sha256(sources[target]).hexdigest() for source,target in SOURCE_FILES.items()}
            == provenance['sources'], 'provenance_mismatch')
    require(not set(sources).intersection(bundled), 'invalid_input')
    destination.mkdir(mode=0o755)
    files = {**sources, **bundled, 'invocation.json':_json(dict(schema=1,lane=LANE,nonce=nonce,provenance=provenance))}
    for name, data in files.items():
        path = destination / name; path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data); path.chmod(0o444)
    verify_inputs(destination, nonce)


def manifest_identity(root):
    root = Path(root)
    raw, manifest = _manifest(root)
    hashes = {name:manifest['files'][name]['sha256'] for name in manifest['runtime_sources']}
    return {'python_version':'.'.join(map(str,sys.version_info[:3])),
        'dependencies':dict(DEPENDENCIES), 'source_file_count':len(hashes),
        'source_sha256':hashlib.sha256(_json(hashes)).hexdigest(),
        'comparison_driver_sha256':hashes['scripts/native_1c_full_host.py'],
        'map_contract_sha256':hashes['scripts/native_1c_map_contract.py'],
        'bundle_manifest_sha256':hashlib.sha256(raw).hexdigest()}


def activate_runtime(root):
    """Must run before importing yadinassi or any bundled dependency module."""
    root = Path(root).resolve()
    invocation = decode(_read(root / 'invocation.json', 32768))
    require(type(invocation) is dict and 'nonce' in invocation, 'invalid_input')
    verify_inputs(root, invocation['nonce'])
    prefixes = ('yadinassi', *PACKAGES.values())
    require(not any(name == p or name.startswith(p + '.') for name in sys.modules for p in prefixes),
            'provenance_mismatch')
    installed = {d.metadata['Name'].lower().replace('_','-'):d.version
                 for d in importlib.metadata.distributions(path=[str(root / 'dependencies')])}
    require(installed == DEPENDENCIES, 'provenance_mismatch')
    sys.path[:0] = [str(root), str(root / 'dependencies')]
    return runtime_identity(invocation['provenance'])


def validate_source_identity(provenance):
    validate_provenance(provenance, provenance)
    require(set(provenance['sources']) == set(SOURCE_FILES), 'provenance_mismatch')
    return provenance


def runtime_identity(provenance):
    validate_source_identity(provenance)
    return {'dependencies':dict(DEPENDENCIES),
            'bundle_manifest_sha256':provenance['sources'][MANIFEST]}
