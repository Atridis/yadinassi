"""Closed full-runtime/dependency bundle for the opt-in public metadata lane.

The compact provenance binds a manifest, not an unverified package version.
The manifest hashes every staged runtime and dependency file, including UCA and
timezone data. This is not a whole-venv copy: generated bytecode/caches and
private installer metadata (direct_url.json, INSTALLER, REQUESTED) are omitted.
.pth injection files and paths outside the four packages/dist-info roots are
rejected. The existing measurement-only inventory remains unchanged.
"""
